--DROP TABLE IF EXISTS silver.automobile

CREATE TABLE silver.automobile (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	date date,
	customer_id VARCHAR,
	first_name VARCHAR,
	last_name VARCHAR,
	phone VARCHAR(20),
	vehicle_type VARCHAR,
	plate_number VARCHAR,
	service_type VARCHAR,
	complaint VARCHAR,
	parts_replaced VARCHAR,
	mechanic_name VARCHAR,
	service_cost INT,
	payment_mode VARCHAR,
	return_visit VARCHAR,
	rating VARCHAR,
	service_time TIME,
	remarks VARCHAR,
	status VARCHAR,
	workshop_location VARCHAR,
	referral_source VARCHAR,
	wait_time_mins INT,
	spare_parts_availability VARCHAR,
	parts_source VARCHAR,
	service_priority VARCHAR,
	customer_type VARCHAR,
	fleet_name VARCHAR,
	mechanic_skill_level VARCHAR,
	parts_cost INT,
	labour_cost INT,
	fuel_topup VARCHAR,
	discount_given INT,
	promo_code_used VARCHAR,
	follow_up_date date,
	has_insurance_cover VARCHAR,
	mechanic_notes VARCHAR,
	customer_notes VARCHAR,
	request_for_pickup VARCHAR,
	home_service VARCHAR,
	towing_required VARCHAR,
	service_package VARCHAR,
	whatsapp_followup VARCHAR
);